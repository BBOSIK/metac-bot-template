def env_list(name: str) -> list[str]:
    return [part.strip() for part in os.getenv(name, "").split(",") if part.strip()]


@dataclass
class Ensemble:
    forecasters: list[GeneralLlm] = field(default_factory=list)
    llms: dict[str, str | GeneralLlm] = field(default_factory=dict)  # llms= overrides
    free_tier: bool = False  # trim LLM calls per question to fit the free daily cap


def build_ensemble() -> Ensemble:
    """Forecasters plus the llms= overrides for the other purposes.

    With no OpenRouter key and no overrides this returns an empty Ensemble, and the bot
    falls back to forecasting-tools defaults (e.g. the Metaculus LLM proxy) with one model.
    """
    use_openrouter = os.getenv("OPENROUTER_API_KEY", "").strip() not in ("", "REPLACE_ME")
    free_tier = use_openrouter and os.getenv("BOT_TIER", "").strip() != "paid"
    default_names = OPENROUTER_FREE_FORECASTERS if free_tier else OPENROUTER_FORECASTERS
    names = env_list("BOT_FORECASTERS") or (default_names if use_openrouter else [])
    forecasters = [
        GeneralLlm(
            model=name,
            temperature=0.3,
            timeout=FORECASTER_TIMEOUT_SECONDS,
            allowed_tries=2,
        )
        for name in names
    ]
    llms: dict[str, str | GeneralLlm] = {}
    researcher = os.getenv("BOT_RESEARCHER", "").strip()
    if not researcher and use_openrouter:
        researcher = "no_research" if free_tier else OPENROUTER_RESEARCHER
    if researcher:
        # no_research, asknews/... and smart-searcher/... are dispatched by name in run_research.
        llms["researcher"] = (
            researcher
            if researcher == "no_research"
            or researcher.startswith(("asknews/", "smart-searcher/"))
            else GeneralLlm(model=researcher, temperature=0.1, timeout=120)
        )
    parser = os.getenv("BOT_PARSER", "").strip()
    if not parser and use_openrouter:
        parser = OPENROUTER_FREE_PARSER if free_tier else OPENROUTER_PARSER
    if parser:
        llms["parser"] = GeneralLlm(model=parser, temperature=0.0)
        llms["summarizer"] = GeneralLlm(model=parser, temperature=0.3)
    if forecasters:
        llms["default"] = forecasters[0]
    return Ensemble(forecasters, llms, free_tier)


class EnsembleBot(ForecastBot):
    """
    Multi-vendor ensemble built on the Metaculus Fall 2026 template bot.
    Each research report gets one forecast from every model in `forecasters`
    (round-robin over prediction slots), and the parent class aggregates them
    (median for binary questions). Everything below this paragraph is the
    template's original documentation.

    This is the template bot for the Fall 2026 FutureEval Bot Tournament.
    This is a copy of what is used by Metaculus to run the Metac Bots in our benchmark, provided as a template for new bot makers.
    This template is given as-is, and is use-at-your-own-risk.
    We have covered most test cases in forecasting-tools it may be worth double checking key components locally.
    So far our track record has been 1 mentionable bug per season (affecting forecasts for 1-2% of total questions)

    This bot is identical to SummerTemplateBot2026.

    The main entry point of this bot is `bot.forecast_on_tournament(tournament_id)` in the parent class.
    See the script at the bottom of the file for more details on how to run the bot.
    Ignoring the finer details, the general flow is:
    - Load questions from Metaculus
    - For each question
        - Execute run_research a number of times equal to research_reports_per_question
        - Execute respective run_forecast function `predictions_per_research_report * research_reports_per_question` times
        - Aggregate the predictions
        - Submit prediction (if publish_reports_to_metaculus is True)
    - Return a list of ForecastReport objects

    Alternatively, you can use the MetaculusClient to make a custom filter of questions to forecast on
    and forecast them with `bot.forecast_questions(questions)`

    Only the research and forecast functions need to be implemented in ForecastBot subclasses,
    though you may want to override other ForecastBot functions.
    In this example, you can change the prompts to be whatever you want since,
    structure_output uses an LLM to intelligently reformat the output into the needed structure.

    By default (i.e. 'tournament' mode), when you run this script, it will forecast on any open questions in the
    primary bot tournament and MiniBench. If you want to forecast on only one or the other, you can remove one
    of them from the 'tournament' mode code at the bottom of the file.

    You can experiment with what models work best with your bot by using the `llms` parameter when initializing the bot.
    You can initialize the bot with any number of models. For example,
    ```python
    my_bot = MyBot(
        ...
        llms={  # choose your model names or GeneralLlm llms here, otherwise defaults will be chosen for you
            "default": GeneralLlm(
                model="openrouter/openai/gpt-4o", # "anthropic/claude-sonnet-4-20250514", etc (see docs for litellm)
                temperature=0.3,
                timeout=40,
                allowed_tries=2,
            ),
            "summarizer": "openai/gpt-4o-mini",
            "researcher": "asknews/news-summaries",
            "parser": "openai/gpt-4o-mini",
        },
    )
    ```

    Then you can access the model in custom functions like this:
    ```python
    research_strategy = self.get_llm("researcher", "model_name")
    if research_strategy == "asknews/news-summaries":
        ...
    # OR
    summarizer = await self.get_llm("summarizer", "llm").invoke(prompt)
    # OR
    reasoning = await self.get_llm("default", "llm").invoke(prompt)
    ```

    If you end up having trouble with rate limits and want to try a more sophisticated rate limiter try:
    ```python
    from forecasting_tools import RefreshingBucketRateLimiter
    rate_limiter = RefreshingBucketRateLimiter(
        capacity=2,
        refresh_rate=1,
    ) # Allows 1 request per second on average with a burst of 2 requests initially. Set this as a class variable
    await self.rate_limiter.wait_till_able_to_acquire_resources(1) # 1 because it's consuming 1 request (use more if you are adding a token limit)
    ```
    Additionally OpenRouter has large rate limits immediately on account creation
    """

    _max_concurrent_questions = (
        1  # Set this to whatever works for your search-provider/ai-model rate limits
    )
    _concurrency_limiter = asyncio.Semaphore(_max_concurrent_questions)
    _structure_output_validation_samples = 2

    def __init__(
        self,
        *args,
        forecasters: list[GeneralLlm] | None = None,
        max_questions_per_run: int | None = None,
        **kwargs,
    ):
        super().__init__(*args, **kwargs)
        self.forecasters = forecasters or []
        self.max_questions_per_run = max_questions_per_run
        self._next_slot: dict[int, int] = {}

    ##################################### ENSEMBLE #####################################

    async def forecast_questions(self, questions, return_exceptions: bool = False):
        if self.max_questions_per_run is not None:
            # Leftovers are picked up by later runs, since forecasted questions are skipped.
            if self.skip_previously_forecasted_questions:
                questions = [q for q in questions if not q.already_forecasted]
            questions = questions[: self.max_questions_per_run]
        return await super().forecast_questions(questions, return_exceptions)

    async def _make_prediction(self, question: MetaculusQuestion, research: str):
        if not self.forecasters:
            return await super()._make_prediction(question, research)
        # No await between read and write, so concurrent slots of one question get distinct indices.
        key = id(question)
        slot = self._next_slot.get(key, 0)
        self._next_slot[key] = slot + 1
        token = _current_forecaster.set(self.forecasters[slot % len(self.forecasters)])
        try:
            return await super()._make_prediction(question, research)
        finally:
            _current_forecaster.reset(token)

    def _forecaster_llm(self) -> GeneralLlm:
        return _current_forecaster.get() or self.get_llm("default", "llm")

    async def _invoke_forecaster(self, question: MetaculusQuestion, prompt: str) -> tuple[str, str]:
        """Returns (reasoning to parse, reasoning to publish tagged with the model name)."""
        llm = self._forecaster_llm()
        reasoning = await llm.invoke(prompt)
        logger.info(f"Reasoning ({llm.model}) for URL {question.page_url}: {reasoning}")
        return reasoning, f"*Model: {llm.model}*\n\n{reasoning}"

    ##################################### RESEARCH #####################################

    async def run_research(self, question: MetaculusQuestion) -> str:
        async with self._concurrency_limiter:
            research = ""
            researcher = self.get_llm("researcher")

            prompt = self._get_research_prompt(question, researcher)

            if isinstance(researcher, GeneralLlm):
                research = await researcher.invoke(prompt)
            elif (
                researcher == "asknews/news-summaries"
                or researcher == "asknews/deep-research/low-depth"
                or researcher == "asknews/deep-research/medium-depth"
                or researcher == "asknews/deep-research/high-depth"
            ):
                research = await AskNewsSearcher().call_preconfigured_version(
                    researcher, prompt
                )
            elif researcher.startswith("smart-searcher"):
                model_name = researcher.removeprefix("smart-searcher/")
                searcher = SmartSearcher(
                    model=model_name,
                    temperature=0,
                    num_searches_to_run=2,
                    num_sites_per_search=10,
                    use_advanced_filters=False,
                )
                research = await searcher.invoke(prompt)
            elif not researcher or researcher == "None" or researcher == "no_research":
                research = ""
            else:
                research = await self.get_llm("researcher", "llm").invoke(prompt)
            logger.info(f"Found Research for URL {question.page_url}:\n{research}")
            return research

    @staticmethod
    def _get_research_prompt(
        question: MetaculusQuestion, researcher: str | GeneralLlm
    ) -> str:
        if GeneralLlm.to_model_name(researcher) == "asknews/news-summaries":
            return question.question_text

        prompt = clean_indents(
            f"""
            You are an assistant to a superforecaster.
            The superforecaster will give you a question they intend to forecast on.
            To be a great assistant, you generate a concise but detailed rundown of the most relevant news, including if the question would resolve Yes or No based on current information.
            You do not produce forecasts yourself.

            Question:
            {question.question_text}

            This question's outcome will be determined by the specific criteria below:
            {question.resolution_criteria}

            {question.fine_print}
            """
        )
        return prompt

    ##################################### BINARY QUESTIONS #####################################

    async def _run_forecast_on_binary(
        self, question: BinaryQuestion, research: str
    ) -> ReasonedPrediction[float]:
        prompt = clean_indents(
            f"""
            You are a professional forecaster interviewing for a job.

            Your interview question is:
            {question.question_text}

            Question background:
            {question.background_info}


            This question's outcome will be determined by the specific criteria below. These criteria have not yet been satisfied:
            {question.resolution_criteria}

            {question.fine_print}


            Your research assistant says:
            {research}

            Today is {datetime.now().strftime("%Y-%m-%d")}.

            Before answering you write:
            (a) The time left until the outcome to the question is known.
            (b) The status quo outcome if nothing changed.
            (c) A brief description of a scenario that results in a No outcome.
            (d) A brief description of a scenario that results in a Yes outcome.

            You write your rationale remembering that good forecasters put extra weight on the status quo outcome since the world changes slowly most of the time.
            {self._get_conditional_disclaimer_if_necessary(question)}

            The last thing you write is your final answer as: "Probability: ZZ%", 0-100
            """
        )

        return await self._binary_prompt_to_forecast(question, prompt)

    async def _binary_prompt_to_forecast(
        self,
        question: BinaryQuestion,
        prompt: str,
    ) -> ReasonedPrediction[float]:
        reasoning, published_reasoning = await self._invoke_forecaster(question, prompt)
        parsing_instructions = clean_indents(
            f"""
            The text given to you is trying to give a probability forecast for a binary question.
            {self._create_resolved_question_parsing_message()}
            """
        )
        binary_prediction: BinaryPrediction = await structure_output(
            reasoning,
            BinaryPrediction,
            model=self.get_llm("parser", "llm"),
            num_validation_samples=self._structure_output_validation_samples,
            additional_instructions=parsing_instructions,
        )
        decimal_pred = max(0.01, min(0.99, binary_prediction.prediction_in_decimal))

        logger.info(
            f"Forecasted URL {question.page_url} with prediction: {decimal_pred}."
        )
        return ReasonedPrediction(
            prediction_value=decimal_pred, reasoning=published_reasoning
        )

